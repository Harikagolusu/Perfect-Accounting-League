import { createFileRoute } from "@tanstack/react-router";
import { useState } from "react";
import { CircleDashed, FileCode, FileSpreadsheet, CheckCircle2, XCircle } from "lucide-react";
import {
  PageHeader,
  Section,
  KV,
  StatusBadge,
  Field,
  InfoNotice,
  EmptyState,
} from "@/components/pal/common";
import { ExportHistory } from "@/components/pal/export-history";
import { ApprovedVoucherExport } from "@/components/pal/approved-voucher-export";
import { CompanyAccountingDefaults, LedgerMaster } from "@/components/pal/ledger-master";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { useCompany, useScoped, useStore } from "@/lib/store";
import { PERIODS } from "@/lib/constants";
import { exportFile } from "@/lib/export";
import { seo } from "@/lib/seo";
import { toast } from "sonner";

export const Route = createFileRoute("/tally")({
  head: () =>
    seo(
      "Tally Integration",
      "Configure Tally Prime voucher and ledger mapping and export vouchers.",
    ),
  component: TallyPage,
});

const selectCls = "h-9 rounded-md border border-input bg-background px-2 text-sm";

function TallyPage() {
  const s = useStore();
  const company = useCompany();
  const mappings = useScoped(s.mappings);
  const [cfg, setCfg] = useState({
    voucherType: "Purchase",
    tallyCompany: company?.legalName ?? "",
    purchaseLedger: "",
    cgst: "",
    sgst: "",
    igst: "",
    parent: "",
  });
  const [period, setPeriod] = useState(s.period);
  const set = (k: keyof typeof cfg, v: string) => setCfg((c) => ({ ...c, [k]: v }));

  if (!company) {
    return (
      <>
        <PageHeader
          title="Tally Integration"
          description="Tally Prime configuration and voucher exports."
        />
        <div className="rounded-md border bg-card p-4">
          <EmptyState
            title="No company selected"
            hint="Create a company before configuring a Tally connection."
          />
        </div>
      </>
    );
  }

  const checks = [
    { label: "Voucher type selected", ok: !!cfg.voucherType },
    { label: "Tax ledgers mapped (CGST / SGST / IGST)", ok: !!(cfg.cgst && cfg.sgst && cfg.igst) },
    { label: "Parent group for creditors set", ok: !!cfg.parent },
    {
      label: "Vendor ledger mappings available",
      ok: mappings.length > 0 && mappings.every((m) => m.status === "Approved"),
    },
  ];

  const rows = mappings
    .filter((m) => m.status === "Approved")
    .map((m) => ({
      LEDGERNAME: m.creditorLedger,
      PARENT: cfg.parent,
      GSTIN: m.vendorKey,
      EXPENSELEDGER: m.expenseLedger,
      TAXLEDGER: m.taxLedger,
    }));
  const run = (format: "XML" | "CSV") => {
    if (!checks.every((c) => c.ok))
      return toast.error("Complete the configuration before exporting.");
    const n = exportFile(format, `Tally_${company.displayName.replace(/\s/g, "")}_${period}`, rows);
    if (n == null) return toast.error("This format is produced by the backend.");
    s.addExport({
      name: `Ledger masters ${period}`,
      type: "Ledger Masters",
      format,
      records: n,
      status: "Generated",
      target: "Tally",
    });
    s.log({
      module: "Tally Integration",
      action: "Exported",
      recordId: `${format}-${period}`,
      previous: "—",
      next: `${n} records`,
    });
    toast.success(`${format} file downloaded (${n} records)`, {
      description:
        format === "XML"
          ? "Review file — final import-ready XML is generated by the backend."
          : undefined,
    });
  };

  return (
    <>
      <PageHeader
        title="Tally Integration"
        description="Tally Prime configuration and voucher exports."
      />
      <InfoNotice>
        No live Tally connection exists. The Tally import settings below are kept in this browser
        session only. The Ledger Master, company ledger defaults and approved voucher export are
        real backend records scoped to the active company.
      </InfoNotice>
      <div className="grid gap-4 lg:grid-cols-3">
        <Section title="Connection Status">
          <div className="mb-3 flex items-center gap-2 text-sm">
            <CircleDashed className="h-4 w-4 text-muted-foreground" />{" "}
            <StatusBadge status="Not connected" />
          </div>
          <KV k="Tally company" v={cfg.tallyCompany} />
          <KV k="Last synchronization" v="Never" />
          <KV
            k="Configuration"
            v={<StatusBadge status={checks.every((c) => c.ok) ? "Approved" : "Pending"} />}
          />
        </Section>
        <Section title="Import Configuration" className="lg:col-span-2">
          <div className="grid gap-3 md:grid-cols-3">
            <Field label="Tally company name">
              <Input
                value={cfg.tallyCompany}
                onChange={(e) => set("tallyCompany", e.target.value)}
              />
            </Field>
            <Field label="Voucher type">
              <select
                className={selectCls}
                value={cfg.voucherType}
                onChange={(e) => set("voucherType", e.target.value)}
              >
                {["Purchase", "Journal", "Payment", "Receipt"].map((x) => (
                  <option key={x}>{x}</option>
                ))}
              </select>
            </Field>
            <Field label="Default ledger">
              <Input
                value={cfg.purchaseLedger}
                onChange={(e) => set("purchaseLedger", e.target.value)}
                placeholder="Tally ledger name"
              />
            </Field>
            <Field label="CGST ledger">
              <Input value={cfg.cgst} onChange={(e) => set("cgst", e.target.value)} />
            </Field>
            <Field label="SGST ledger">
              <Input value={cfg.sgst} onChange={(e) => set("sgst", e.target.value)} />
            </Field>
            <Field label="IGST ledger">
              <Input value={cfg.igst} onChange={(e) => set("igst", e.target.value)} />
            </Field>
            <Field label="Parent group mapping">
              <Input value={cfg.parent} onChange={(e) => set("parent", e.target.value)} />
            </Field>
          </div>
          <div className="mt-3">
            <Button
              variant="outline"
              onClick={() => toast.success("Configuration saved in this browser session")}
            >
              Save configuration
            </Button>
          </div>
        </Section>
        <Section title="Validation Status">
          {checks.map((c) => (
            <div
              key={c.label}
              className="flex items-center gap-2 border-b py-2 text-sm last:border-0"
            >
              {c.ok ? (
                <CheckCircle2 className="h-4 w-4 text-success" />
              ) : (
                <XCircle className="h-4 w-4 text-destructive" />
              )}
              {c.label}
            </div>
          ))}
        </Section>
        <Section title="Export Configuration">
          <div className="grid gap-3">
            <Field label="Company">
              <Input readOnly value={company.displayName} />
            </Field>
            <Field label="Financial period">
              <select
                className={selectCls}
                value={period}
                onChange={(e) => setPeriod(e.target.value)}
              >
                {PERIODS.map((p) => (
                  <option key={p}>{p}</option>
                ))}
              </select>
            </Field>
            <div className="flex flex-wrap gap-2">
              <Button onClick={() => run("XML")}>
                <FileCode />
                Export Tally XML
              </Button>
              <Button variant="outline" onClick={() => run("CSV")}>
                <FileSpreadsheet />
                Export CSV
              </Button>
            </div>
          </div>
        </Section>
        <LedgerMaster key={`ledgers-${company.id}`} companyId={company.id} />
        <CompanyAccountingDefaults key={`defaults-${company.id}`} companyId={company.id} />
        <ApprovedVoucherExport key={`export-${company.id}`} companyId={company.id} />
        <Section title="Setup Guide">
          <ol className="list-decimal space-y-1.5 pl-5 text-sm text-muted-foreground">
            <li>Enable Tally Prime ODBC / XML server (Help → Settings → Connectivity).</li>
            <li>Confirm the Tally company name matches exactly.</li>
            <li>Add the company's ledgers and map tax, round-off and sales defaults.</li>
            <li>Approve draft vouchers before generating the client accounting workbook.</li>
            <li>Export and import via Gateway of Tally, then verify the posted voucher.</li>
          </ol>
        </Section>
        <div className="lg:col-span-3">
          <h2 className="mb-2 text-sm font-semibold">Export History</h2>
          <ExportHistory target="Tally" />
        </div>
      </div>
    </>
  );
}
